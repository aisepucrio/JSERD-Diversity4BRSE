## category Q29

"""

df['report_category_clean'] = (
    df['report_category']
    .fillna('')
    .astype(str)
    .str.lower()
    .str.strip()
)

df_clean = df[df['report_category_clean'].apply(len) > 0]

df_clean['report_category_list'] = df_clean['report_category_clean'].apply(
    lambda x: [i.strip() for i in x.split(', ') if i.strip() != '']
)

"""### Distribution categories"""

from collections import Counter

# Flatten das categorias
all_tags = [tag for sublist in df_clean['report_category_list'] for tag in sublist]

# Contagem
tag_counts = Counter(all_tags)

# Total de ocorrências
total = sum(tag_counts.values())

# Converter para porcentagem
tag_percent = {
    k: (v / total) * 100
    for k, v in tag_counts.items()
}

# Plot
plt.figure(figsize=(8, 5))
plt.bar(tag_percent.keys(), tag_percent.values())

plt.ylabel("Percentage (%)")
plt.xticks(rotation=45, ha="right")
plt.title("Distribution of Discrimination Categories")
plt.tight_layout()
plt.savefig(f'{output_dir}barplot_cat.png', bbox_inches="tight")


